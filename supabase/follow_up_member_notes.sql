-- Member notes log for the Red / Orange Follow-Up report.
--
-- One running notes thread per member, kept across reports (a report's own
-- top-level note is cleared when the nightly bot builds a new report; this log
-- keeps every note). Members are matched by fuKey(name): trimmed, lower-cased.
-- Everyone with follow-up access reads; the author is set by the database. On the
-- day a note is written, anyone with edit access can edit it (stamped) and its
-- author can delete it; after that day it is permanent.
--
-- Safe to re-run. Run in the Supabase SQL editor (after access_control.sql).
-- Rollback: drop table public.follow_up_member_notes; drop function public.follow_up_note_is_today(timestamptz);

create table if not exists public.follow_up_member_notes (
  id bigint generated by default as identity primary key,
  member_key text not null,
  member_name text,
  note text not null check (char_length(btrim(note)) between 1 and 2000),
  author text default (auth.jwt() ->> 'email'),
  created_at timestamptz not null default now(),
  edited_by text,
  edited_at timestamptz
);

create index if not exists follow_up_member_notes_member_idx
  on public.follow_up_member_notes (member_key, created_at desc);

revoke all on table public.follow_up_member_notes from anon;
alter table public.follow_up_member_notes enable row level security;

drop policy if exists "Staff read follow-up notes" on public.follow_up_member_notes;
create policy "Staff read follow-up notes" on public.follow_up_member_notes
  for select to authenticated using (true);

drop policy if exists "Staff add follow-up notes" on public.follow_up_member_notes;
create policy "Staff add follow-up notes" on public.follow_up_member_notes
  for insert to authenticated with check (author = auth.jwt() ->> 'email');

-- Notes can be edited (by anyone with edit access) or deleted (by their author) only on
-- the day they were written, Sydney time. After that day they are permanent.
create or replace function public.follow_up_note_is_today(stamp timestamptz)
returns boolean
language sql
stable
set search_path = ''
as $$
  select (stamp at time zone 'Australia/Sydney')::date = (now() at time zone 'Australia/Sydney')::date
$$;

drop policy if exists "Staff edit follow-up notes" on public.follow_up_member_notes;
create policy "Staff edit follow-up notes" on public.follow_up_member_notes
  for update to authenticated using (public.follow_up_note_is_today(created_at)) with check (true);

drop policy if exists "Staff delete own follow-up notes" on public.follow_up_member_notes;
create policy "Staff delete own follow-up notes" on public.follow_up_member_notes
  for delete to authenticated using (author = auth.jwt() ->> 'email' and public.follow_up_note_is_today(created_at));

-- Inserts set only these columns, so the author and time always come from the database.
revoke all on table public.follow_up_member_notes from anon, authenticated;
grant select, delete on table public.follow_up_member_notes to authenticated;
grant insert (member_key, member_name, note) on table public.follow_up_member_notes to authenticated;
grant update (note) on table public.follow_up_member_notes to authenticated;

-- Editing keeps the original author, member and date; the database stamps who edited and when.
create or replace function public.follow_up_member_notes_stamp_edit()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.id := old.id;
  new.member_key := old.member_key;
  new.member_name := old.member_name;
  new.author := old.author;
  new.created_at := old.created_at;
  new.edited_by := auth.jwt() ->> 'email';
  new.edited_at := now();
  return new;
end
$$;

drop trigger if exists follow_up_member_notes_stamp_edit on public.follow_up_member_notes;
create trigger follow_up_member_notes_stamp_edit
  before update on public.follow_up_member_notes
  for each row execute function public.follow_up_member_notes_stamp_edit();

-- Roles and permissions (same as every Red / Orange table in access_control.sql):
-- followup.view to read, followup.edit to add, edit or delete.
drop policy if exists "Role can view" on public.follow_up_member_notes;
create policy "Role can view" on public.follow_up_member_notes as restrictive
  for select to authenticated using ((select public.has_permission('followup.view')));
drop policy if exists "Role can add" on public.follow_up_member_notes;
create policy "Role can add" on public.follow_up_member_notes as restrictive
  for insert to authenticated with check ((select public.has_permission('followup.edit')));
drop policy if exists "Role can change" on public.follow_up_member_notes;
create policy "Role can change" on public.follow_up_member_notes as restrictive
  for update to authenticated using ((select public.has_permission('followup.edit'))) with check ((select public.has_permission('followup.edit')));
drop policy if exists "Role can remove" on public.follow_up_member_notes;
create policy "Role can remove" on public.follow_up_member_notes as restrictive
  for delete to authenticated using ((select public.has_permission('followup.edit')));

-- One-time copy: top-level notes typed before this log existed (on the latest report) go into
-- the log, so they are not lost when the next day's report starts with clear notes.
-- Skips any already copied. Author shows as "Earlier report note".
insert into public.follow_up_member_notes (member_key, member_name, note, author, created_at)
select n.key,
       coalesce((select a ->> 'name' from jsonb_array_elements(r.attendance) a
                 where lower(regexp_replace(btrim(a ->> 'name'), '\s+', ' ', 'g')) = n.key limit 1), n.key),
       left(btrim(n.value), 2000),
       'Earlier report note',
       r.updated_at
from (select * from public.follow_up_reports order by report_date desc, created_at desc limit 1) r,
     jsonb_each_text(r.notes) n
where btrim(n.value) <> ''
  and not exists (select 1 from public.follow_up_member_notes m where m.member_key = n.key and m.note = left(btrim(n.value), 2000));


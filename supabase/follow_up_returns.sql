-- Returned log for the Red / Orange Follow-Up report.
--
-- One row per member per return: they were on a report's follow-up list and dropped off
-- the next one because they trained again (membership not on HOLD, Gratis or cancelled).
-- Written by the nightly bot and by uploads on the Upload tab (fuReturns in js/followUpCore.js).
-- Staff can take a wrong match off the list (soft remove), only on the day it was recorded.
--
-- Safe to re-run. Run in the Supabase SQL editor (after access_control.sql).
-- Rollback: drop table public.follow_up_returns; drop function public.follow_up_returns_stamp();

create table if not exists public.follow_up_returns (
  id bigint generated by default as identity primary key,
  member_key text not null,
  member_name text not null,
  phone text,
  returned_on date not null,                  -- their new last class
  last_class_before date,                     -- last class while they were on the list
  tier text,                                  -- orange | red | none, on the last list they were on
  days integer,                               -- days away on that list
  membership_label text,
  report_id bigint references public.follow_up_reports (id) on delete set null,
  detected_at timestamptz not null default now(),
  removed_at timestamptz,
  removed_by text,
  unique (member_key, returned_on)            -- a same-day refresh never records a return twice
);

create index if not exists follow_up_returns_returned_idx on public.follow_up_returns (returned_on desc);

revoke all on table public.follow_up_returns from anon, authenticated;
alter table public.follow_up_returns enable row level security;

drop policy if exists "Staff read returns" on public.follow_up_returns;
create policy "Staff read returns" on public.follow_up_returns
  for select to authenticated using (true);

drop policy if exists "Staff record returns" on public.follow_up_returns;
create policy "Staff record returns" on public.follow_up_returns
  for insert to authenticated with check (true);

-- Removing is the only change allowed, and only on the day the return was recorded (Sydney).
drop policy if exists "Staff remove returns same day" on public.follow_up_returns;
create policy "Staff remove returns same day" on public.follow_up_returns
  for update to authenticated
  using (removed_at is null and (detected_at at time zone 'Australia/Sydney')::date = (now() at time zone 'Australia/Sydney')::date)
  with check (true);

grant select on table public.follow_up_returns to authenticated;
grant insert (member_key, member_name, phone, returned_on, last_class_before, tier, days, membership_label, report_id)
  on table public.follow_up_returns to authenticated;
grant update (removed_at) on table public.follow_up_returns to authenticated;

-- Who removed it and when come from the database; nothing else on the row can change.
-- Deleting a report sets report_id to null (foreign key): let that through, and never
-- count it as a removal.
create or replace function public.follow_up_returns_stamp()
returns trigger
language plpgsql
set search_path = ''
as $$
declare
  report_cleared boolean := new.report_id is null and old.report_id is not null;
  removing boolean := new.removed_at is not null and old.removed_at is null;
begin
  new := old;
  if report_cleared then
    new.report_id := null;
  end if;
  if removing then
    new.removed_at := now();
    new.removed_by := auth.jwt() ->> 'email';
  end if;
  return new;
end
$$;

drop trigger if exists follow_up_returns_stamp on public.follow_up_returns;
create trigger follow_up_returns_stamp
  before update on public.follow_up_returns
  for each row execute function public.follow_up_returns_stamp();

-- Roles and permissions, as for the other Red / Orange tables in access_control.sql.
drop policy if exists "Role can view" on public.follow_up_returns;
create policy "Role can view" on public.follow_up_returns as restrictive
  for select to authenticated using ((select public.has_permission('followup.view')));
drop policy if exists "Role can add" on public.follow_up_returns;
create policy "Role can add" on public.follow_up_returns as restrictive
  for insert to authenticated with check ((select public.has_permission('followup.edit')));
drop policy if exists "Role can change" on public.follow_up_returns;
create policy "Role can change" on public.follow_up_returns as restrictive
  for update to authenticated using ((select public.has_permission('followup.edit'))) with check ((select public.has_permission('followup.edit')));


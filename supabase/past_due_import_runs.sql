-- One row per Past Due import: the page's "Import billing CSV" or the Zen Planner sync
-- (automation/zenplanner-pastdue.mjs). The page shows the latest one as "Last import", so an
-- import that only found bills already on file still counts.
--
-- Safe to re-run. Run in the Supabase SQL editor.

create table if not exists public.past_due_import_runs (
  id bigint generated by default as identity primary key,
  ran_at timestamptz not null default now(),
  source text not null check (source in ('csv', 'zen planner')),
  bills_found integer not null default 0 check (bills_found >= 0),
  bills_added integer not null default 0 check (bills_added >= 0),
  bills_cleared integer not null default 0 check (bills_cleared >= 0),
  run_by text default (auth.jwt() ->> 'email')
);

create index if not exists past_due_import_runs_ran_at_idx on public.past_due_import_runs (ran_at desc);

-- Signed-in staff only: read all runs, add runs as themselves. No edits or deletes.
revoke all on table public.past_due_import_runs from anon;
alter table public.past_due_import_runs enable row level security;

drop policy if exists "Staff read import runs" on public.past_due_import_runs;
create policy "Staff read import runs" on public.past_due_import_runs
  for select to authenticated using (true);

drop policy if exists "Staff add import runs" on public.past_due_import_runs;
create policy "Staff add import runs" on public.past_due_import_runs
  for insert to authenticated with check (run_by = auth.jwt() ->> 'email');

-- Staff may only fill the counts; ran_at and run_by always come from the database,
-- so nobody can post-date a run and pin the page's "Last import" line.
revoke insert on table public.past_due_import_runs from authenticated;
grant select on table public.past_due_import_runs to authenticated;
grant insert (source, bills_found, bills_added, bills_cleared) on table public.past_due_import_runs to authenticated;

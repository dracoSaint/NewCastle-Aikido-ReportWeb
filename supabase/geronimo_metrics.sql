-- Geronimo Metrics Report (was the "GRN_Metrics" Google Sheet).
--
--   geronimo_weekly         one row per week (ending Friday): the Dashboard tab's figures as entered.
--                           Percentages and averages are worked out on the page, not stored.
--   geronimo_wave_members   the monthly trial waves: who was inducted and whether they rolled over.
--   geronimo_scoreboard     one row per day: rollovers, memberships, organic leads, cancels, kickstarts.
--
-- Wave members hold names, emails and phone numbers, so every table is signed-in staff only, behind
-- the "Geronimo Metrics" switches (geronimo.view / geronimo.edit) from supabase/access_control.sql.
-- Run after access_control.sql. Safe to re-run. History: supabase/geronimo_metrics_seed.sql.

create table if not exists public.geronimo_weekly (
  week_ending date primary key check (extract(isodow from week_ending) = 5), -- a Friday
  revenue_30d numeric(12, 2),        -- Rolling 30 day revenue
  autopay_members integer,
  suspended_members integer,
  fb_spend numeric(12, 2),           -- Facebook budget spent
  meta_leads integer,                -- # of Meta paid leads
  organic_leads integer,
  intro_pack_sales integer,          -- # Intro + Pack sales
  membership_sales integer,          -- membership sales this week
  sales_value numeric(12, 2),
  rollovers integer,
  rollover_pct numeric(6, 4),        -- fraction: 0.8 = 80%
  attendance integer,
  weekly_cancels integer,
  cancels_mtd integer,               -- cancels month to date
  updated_at timestamptz not null default now(),
  updated_by text default (auth.jwt() ->> 'email')
);
-- Set by the nightly bot once the week has ended and its figures are saved; staff can still edit a locked week.
alter table public.geronimo_weekly add column if not exists locked_at timestamptz;

create table if not exists public.geronimo_wave_members (
  id bigint generated by default as identity primary key,
  wave_month date not null check (extract(day from wave_month) = 1), -- first of the month
  induction_date date,
  inducted boolean not null default false,
  first_name text not null,
  last_name text,
  email text,
  phone text,
  goal text,
  why text,
  notes text,
  rolled_over boolean,               -- null = not decided yet
  created_at timestamptz not null default now(),
  created_by text default (auth.jwt() ->> 'email'),
  updated_at timestamptz not null default now(),
  updated_by text default (auth.jwt() ->> 'email')
);

create index if not exists geronimo_wave_members_month_idx on public.geronimo_wave_members (wave_month);
-- Starters added from the Monday Board member list carry their Zen Planner member number:
-- one row per member per wave, so adding them again never duplicates anyone.
alter table public.geronimo_wave_members add column if not exists member_number text;
create unique index if not exists geronimo_wave_members_number_idx on public.geronimo_wave_members (wave_month, member_number);

create table if not exists public.geronimo_scoreboard (
  day date primary key,
  rollovers integer not null default 0,
  memberships integer not null default 0,
  organic_leads integer not null default 0,
  cancels integer not null default 0,
  kickstarts integer not null default 0,
  updated_at timestamptz not null default now(),
  updated_by text default (auth.jwt() ->> 'email')
);
-- Rolling 30 day revenue read off the bank each day; the week's figure is the average of the days entered.
alter table public.geronimo_scoreboard add column if not exists revenue_30d numeric(12, 2);

-- Who last changed a row is stamped by the database.
create or replace function public.geronimo_stamp()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  new.updated_by := auth.jwt() ->> 'email';
  return new;
end
$$;

do $$
declare
  t text;
  ev text;
begin
  foreach t in array array['geronimo_weekly', 'geronimo_wave_members', 'geronimo_scoreboard'] loop
    execute format('drop trigger if exists geronimo_stamp on public.%I', t);
    execute format('create trigger geronimo_stamp before update on public.%I for each row execute function public.geronimo_stamp()', t);

    execute format('revoke all on table public.%I from anon', t);
    execute format('alter table public.%I enable row level security', t);
    execute format('grant select, insert, update, delete on table public.%I to authenticated', t);
    -- Base rule, then the role switches narrow it (same as every report table).
    execute format('drop policy if exists "Signed-in staff" on public.%I', t);
    execute format('create policy "Signed-in staff" on public.%I for all to authenticated using (true) with check (true)', t);
    execute format('drop policy if exists "Role can view" on public.%I', t);
    execute format('create policy "Role can view" on public.%I as restrictive for select to authenticated using ((select public.has_permission(%L)))', t, 'geronimo.view');
    execute format('drop policy if exists "Role can add" on public.%I', t);
    execute format('create policy "Role can add" on public.%I as restrictive for insert to authenticated with check ((select public.has_permission(%L)))', t, 'geronimo.edit');
    execute format('drop policy if exists "Role can change" on public.%I', t);
    execute format('create policy "Role can change" on public.%I as restrictive for update to authenticated using ((select public.has_permission(%L))) with check ((select public.has_permission(%L)))', t, 'geronimo.edit', 'geronimo.edit');
    execute format('drop policy if exists "Role can remove" on public.%I', t);
    execute format('create policy "Role can remove" on public.%I as restrictive for delete to authenticated using ((select public.has_permission(%L)))', t, 'geronimo.edit');

    -- Audit log (supabase/access_control.sql section 8): one line per statement.
    foreach ev in array array['insert', 'update', 'delete'] loop
      execute format('drop trigger if exists app_audit_%s on public.%I', ev, t);
      execute format(
        'create trigger app_audit_%1$s after %1$s on public.%2$I referencing %3$s for each statement execute function public.app_audit_rows()',
        ev, t,
        case ev when 'insert' then 'new table as new_rows' when 'delete' then 'old table as old_rows' else 'old table as old_rows new table as new_rows' end
      );
    end loop;
  end loop;
end
$$;

-- Owner and Staff get the new switches. First run only: once any role has a Geronimo switch, re-running
-- never turns them back on.
insert into public.app_role_permissions (role_key, permission)
select v.role_key, v.permission from (values
  ('owner', 'geronimo.view'), ('owner', 'geronimo.edit'),
  ('staff', 'geronimo.view'), ('staff', 'geronimo.edit')
) as v(role_key, permission)
where not exists (select 1 from public.app_role_permissions where permission like 'geronimo.%')
on conflict do nothing;

-- Bot saves each week's attendance and cancels and locks finished weeks (automation/zenplanner-followup.mjs),
-- reading Daily Ad Review for the spend and leads. Added once, also when the lines above already ran.
insert into public.app_role_permissions (role_key, permission)
select 'bot', v.permission from (values ('geronimo.view'), ('geronimo.edit'), ('ads.view')) as v(permission)
where not exists (select 1 from public.app_role_permissions where role_key = 'bot' and permission like 'geronimo.%')
on conflict do nothing;

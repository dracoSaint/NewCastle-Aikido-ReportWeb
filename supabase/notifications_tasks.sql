-- Notification centre (bell in the header), @mentions in notes, and the task list on the Home page.
--
-- notifications: one row per person per alert. You only see, mark read or clear your own. Anyone
--   signed in can send one (an @mention in a note, a task assigned to you); the sender is set by the
--   database and links can only point inside the portal.
-- tasks: one-off or repeating (daily, weekdays, weekly, monthly). assigned_to empty = whole team.
--   Everyone sees every task; the creator, the assignee or a user admin can change or delete it.
-- task_done: one row per task per day ticked off. A one-off task is done once it has any row.
--
-- Safe to re-run. Run in the Supabase SQL editor (after access_control.sql).
-- Rollback: drop table public.task_comments, public.task_done, public.tasks, public.notifications;
--   drop function public.portal_people(), public.task_done_notify(), public.notify_my_due_tasks();

-- People you can tag or assign to (auth.users is not readable from the browser).
create or replace function public.portal_people()
returns table (user_id uuid, email text, name text)
language sql stable security definer set search_path = public as $$
  select u.id, u.email::text, coalesce(nullif(btrim(u.raw_user_meta_data ->> 'full_name'), ''), split_part(u.email::text, '@', 1))
  from auth.users u
  where auth.uid() is not null
    and not exists (select 1 from public.app_user_roles r where r.user_id = u.id and r.role_key = 'bot')
  order by 3
$$;
revoke all on function public.portal_people() from public, anon;
grant execute on function public.portal_people() to authenticated;

-- 1. Notifications -------------------------------------------------------------------------------

create table if not exists public.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  kind text not null default 'mention' check (kind in ('mention', 'task')),
  title text not null check (char_length(btrim(title)) between 1 and 200),
  body text check (char_length(body) <= 500),
  link text check (link ~ '^(index\.html|pages/[A-Za-z/]+\.html)(\?[A-Za-z0-9=&_.%-]*)?$'),
  created_by text default (auth.jwt() ->> 'email'),
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index if not exists notifications_user_idx on public.notifications (user_id, created_at desc);

alter table public.notifications enable row level security;

drop policy if exists "Read own notifications" on public.notifications;
create policy "Read own notifications" on public.notifications
  for select to authenticated using (user_id = auth.uid());
drop policy if exists "Send notifications" on public.notifications;
create policy "Send notifications" on public.notifications
  for insert to authenticated with check (created_by = auth.jwt() ->> 'email');
drop policy if exists "Mark own notifications" on public.notifications;
create policy "Mark own notifications" on public.notifications
  for update to authenticated using (user_id = auth.uid()) with check (user_id = auth.uid());
drop policy if exists "Clear own notifications" on public.notifications;
create policy "Clear own notifications" on public.notifications
  for delete to authenticated using (user_id = auth.uid());

revoke all on table public.notifications from anon, authenticated;
grant select, delete on table public.notifications to authenticated;
grant insert (user_id, kind, title, body, link) on table public.notifications to authenticated;
grant update (read_at) on table public.notifications to authenticated;

-- 2. Tasks ---------------------------------------------------------------------------------------

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null check (char_length(btrim(title)) between 1 and 200),
  details text check (char_length(details) <= 2000),
  assigned_to uuid references auth.users(id) on delete set null,
  repeat text not null default 'none' check (repeat in ('none', 'daily', 'weekdays', 'weekly', 'monthly')),
  start_date date not null default ((now() at time zone 'Australia/Sydney')::date), -- due date for one-off tasks
  created_by text default (auth.jwt() ->> 'email'),
  created_by_id uuid default auth.uid(),
  created_at timestamptz not null default now()
);

create table if not exists public.task_done (
  task_id bigint not null references public.tasks(id) on delete cascade,
  done_on date not null,
  done_by text default (auth.jwt() ->> 'email'),
  done_at timestamptz not null default now(),
  primary key (task_id, done_on)
);

alter table public.tasks enable row level security;
alter table public.task_done enable row level security;

drop policy if exists "Staff read tasks" on public.tasks;
create policy "Staff read tasks" on public.tasks for select to authenticated using (true);
drop policy if exists "Staff add tasks" on public.tasks;
create policy "Staff add tasks" on public.tasks for insert to authenticated
  with check (created_by_id = auth.uid());
drop policy if exists "Owner changes tasks" on public.tasks;
create policy "Owner changes tasks" on public.tasks for update to authenticated
  using (created_by_id = auth.uid() or assigned_to = auth.uid() or public.has_permission('access.manage'))
  with check (true);
drop policy if exists "Owner deletes tasks" on public.tasks;
create policy "Owner deletes tasks" on public.tasks for delete to authenticated
  using (created_by_id = auth.uid() or assigned_to = auth.uid() or public.has_permission('access.manage'));

drop policy if exists "Staff read ticks" on public.task_done;
create policy "Staff read ticks" on public.task_done for select to authenticated using (true);
drop policy if exists "Staff tick tasks" on public.task_done;
create policy "Staff tick tasks" on public.task_done for insert to authenticated
  with check (done_by = auth.jwt() ->> 'email');
drop policy if exists "Staff untick tasks" on public.task_done;
create policy "Staff untick tasks" on public.task_done for delete to authenticated using (true);

revoke all on table public.tasks, public.task_done from anon, authenticated;
grant select, delete on table public.tasks, public.task_done to authenticated;
grant insert (title, details, assigned_to, repeat, start_date) on table public.tasks to authenticated;
grant update (title, details, assigned_to, repeat, start_date) on table public.tasks to authenticated;
grant insert (task_id, done_on) on table public.task_done to authenticated;


-- Done alerts: ticking off a task someone else made tells the person who made it.
create or replace function public.task_done_notify() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  t public.tasks;
begin
  select * into t from public.tasks where id = new.task_id;
  if t.created_by_id is not null and t.created_by_id is distinct from auth.uid() then
    insert into public.notifications (user_id, kind, title, link, created_by)
    values (t.created_by_id, 'done',
            left(coalesce(split_part(auth.jwt() ->> 'email', '@', 1), 'Someone') || ' finished: ' || t.title, 200),
            'pages/Tasks.html', auth.jwt() ->> 'email');
  end if;
  return new;
end
$$;
revoke all on function public.task_done_notify() from public, anon, authenticated;
drop trigger if exists task_done_notify on public.task_done;
create trigger task_done_notify after insert on public.task_done for each row execute function public.task_done_notify();

-- Due alerts: called by the portal the first time you open it each day. One alert per one-off task
-- of yours (assigned to you) that is due today or overdue and not done; never twice on the same day.
create or replace function public.notify_my_due_tasks() returns integer
language plpgsql security definer set search_path = public as $$
declare
  today date := (now() at time zone 'Australia/Sydney')::date;
  added integer;
begin
  if auth.uid() is null then return 0; end if;
  insert into public.notifications (user_id, kind, title, link, created_by)
  select auth.uid(), 'due',
         left(case when t.start_date < today then 'Overdue: ' else 'Due today: ' end || t.title, 200),
         'pages/Tasks.html', 'tasks'
  from public.tasks t
  where t.assigned_to = auth.uid() and t.repeat = 'none' and t.start_date <= today
    and not exists (select 1 from public.task_done d where d.task_id = t.id)
    and not exists (select 1 from public.notifications n
                    where n.user_id = auth.uid() and n.kind = 'due'
                      and (n.created_at at time zone 'Australia/Sydney')::date = today
                      and right(n.title, length(t.title)) = t.title);
  get diagnostics added = row_count;
  return added;
end
$$;
revoke all on function public.notify_my_due_tasks() from public, anon;
grant execute on function public.notify_my_due_tasks() to authenticated;

